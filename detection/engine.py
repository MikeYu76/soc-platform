from common.detection import Detection
from common.event import Event
from detection.base import DetectionRule


class DetectionEngine:
    """
    Executes detection rules against normalized events.
    """

    def __init__(self, rules: list[DetectionRule]):
        """
        Initialize the engine with a collection of detection rules.

        Args:
            rules: The rules the engine will evaluate against events.
        """
        self.rules = rules

    def detect(self, event: Event) -> list[Detection]:
        """
        Evaluate an event against every detection rule.

        Args:
            event: The canonical Event to evaluate.

        Returns:
            A list of Detection objects generated by matching rules.
        """
        detections = []

        for rule in self.rules:
            detection = rule.match(event)

            if detection is not None:
                detections.append(detection)

        return detections