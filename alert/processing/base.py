from abc import ABC, abstractmethod

from alert.models import Alert


class AlertProcessor(ABC):
    """
    Base interface for post-generation alert processors.

    Alert processors transform alerts after they have been
    generated by AlertRules. Examples include deduplication,
    suppression, grouping, and routing.
    """

    @abstractmethod
    def process(
        self,
        alerts: list[Alert],
    ) -> list[Alert]:
        """
        Process a collection of alerts.
        """
        raise NotImplementedError